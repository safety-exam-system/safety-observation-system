"use client";

import { useCallback, useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import { createClient } from "../../lib/supabase";

type Site = {
  id: string;
  site_code: string;
  site_name: string;
  created_at: string;
};

export default function SiteSelectionPage() {
  const router = useRouter();
  const [supabase] = useState(() => createClient());

  const [activeOption, setActiveOption] = useState<
    "choose" | "add" | ""
  >("");

  const [sites, setSites] = useState<Site[]>([]);
  const [siteName, setSiteName] = useState("");
  const [siteCode, setSiteCode] = useState("");

  const [loading, setLoading] = useState(false);
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState("");
  const [success, setSuccess] = useState("");

  const generateSiteCode = (value: string) => {
    return value
      .trim()
      .replace(/[^a-zA-Z0-9]/g, "")
      .substring(0, 3)
      .toUpperCase();
  };

  const loadSites = useCallback(async () => {
    setLoading(true);
    setError("");

    try {
      const { data, error } = await supabase
        .from("sites")
        .select("id, site_code, site_name, created_at")
        .order("site_name", { ascending: true });

      if (error) throw error;

      setSites((data || []) as Site[]);
    } catch (err) {
      console.error("Load Sites Error:", err);
      setError("Unable to load registered Sites. Please try again.");
    } finally {
      setLoading(false);
    }
  }, [supabase]);

  useEffect(() => {
    if (activeOption === "choose") {
      void loadSites();
    }
  }, [activeOption, loadSites]);

  function handleSiteNameChange(value: string) {
    setSiteName(value);
    setSiteCode(generateSiteCode(value));
    setError("");
    setSuccess("");
  }

  async function handleRegisterSite(
    event: React.FormEvent<HTMLFormElement>
  ) {
    event.preventDefault();

    setError("");
    setSuccess("");

    const name = siteName.trim();
    const code = generateSiteCode(name);

    if (!name) {
      setError("Please enter Site Name.");
      return;
    }

    if (code.length !== 3) {
      setError(
        "Site Name must generate a 3-character Site Code."
      );
      return;
    }

    setSaving(true);

    try {
      // Check whether this Site Code already exists.
      const { data: existingSite, error: checkError } =
        await supabase
          .from("sites")
          .select("id, site_name")
          .eq("site_code", code)
          .maybeSingle();

      if (checkError) throw checkError;

      if (existingSite) {
        setError(
          `Site Code "${code}" is already assigned to "${existingSite.site_name}". Please use a different Site Name.`
        );
        return;
      }

      // Register the new Site.
      // id and created_at are generated by Supabase.
      // company_id remains NULL for now.
      const { data, error: insertError } = await supabase
        .from("sites")
        .insert({
          site_name: name,
          site_code: code,
          company_id: null,
        })
        .select("id, site_code, site_name, created_at")
        .single();

      if (insertError) {
        if (insertError.code === "23505") {
          setError(
            `Site Code "${code}" already exists. Please use a different Site Name.`
          );
          return;
        }

        throw insertError;
      }

      setSuccess(
        `Site "${data.site_name}" registered successfully. Site Code: ${data.site_code}`
      );

      setSiteName("");
      setSiteCode("");

      // Refresh the registered Site list.
      await loadSites();
    } catch (err) {
      console.error("Register Site Error:", err);
      setError("Unable to register Site. Please try again.");
    } finally {
      setSaving(false);
    }
  }

  function openSiteDashboard(site: Site) {
  const params = new URLSearchParams({
    siteCode: site.site_code,
    siteName: site.site_name,
  });

  router.push(`/site-access?${params.toString()}`);
}

  function resetSelection() {
    setActiveOption("");
    setSiteName("");
    setSiteCode("");
    setError("");
    setSuccess("");
  }

  return (
    <main className="min-h-screen bg-slate-100 px-4 py-10">
      <section className="mx-auto w-full max-w-2xl rounded-2xl border border-slate-200 bg-white p-6 shadow-lg sm:p-8">

        {/* Header */}
        <div className="mb-8 text-center">
          <div className="mx-auto mb-4 flex h-16 w-16 items-center justify-center rounded-2xl bg-blue-700 text-3xl text-white">
            🦺
          </div>

          <h1 className="text-2xl font-bold text-slate-900">
            Site Selection Portal
          </h1>

          <p className="mt-2 text-sm text-slate-600">
            Select or register a Site to continue
          </p>
        </div>

        {/* Main Options */}
        {!activeOption && (
          <div className="space-y-4">
            <button
              type="button"
              onClick={() => setActiveOption("choose")}
              className="w-full rounded-xl bg-blue-700 px-4 py-6 text-lg font-semibold text-white transition hover:bg-blue-800"
            >
              Choose Site
            </button>

            <button
              type="button"
              onClick={() => setActiveOption("add")}
              className="w-full rounded-xl bg-emerald-600 px-4 py-6 text-lg font-semibold text-white transition hover:bg-emerald-700"
            >
              Add New Site
            </button>
          </div>
        )}

        {/* Choose Site */}
        {activeOption === "choose" && (
          <div>
            <div className="mb-5 flex items-center justify-between gap-3">
              <h2 className="text-xl font-bold text-slate-800">
                Registered Sites
              </h2>

              <button
                type="button"
                onClick={() => void loadSites()}
                disabled={loading}
                className="rounded-lg border border-blue-200 px-3 py-2 text-sm font-medium text-blue-700 hover:bg-blue-50 disabled:opacity-50"
              >
                Refresh
              </button>
            </div>

            {loading && (
              <p className="py-8 text-center text-slate-600">
                Loading Sites...
              </p>
            )}

            {error && (
              <p
                role="alert"
                className="mb-4 rounded-lg bg-red-50 p-3 text-sm text-red-700"
              >
                {error}
              </p>
            )}

            {!loading && sites.length === 0 && !error && (
              <div className="rounded-xl bg-amber-50 p-5 text-center">
                <p className="font-medium text-amber-800">
                  No registered Sites found.
                </p>

                <p className="mt-2 text-sm text-amber-700">
                  Please use Add New Site to register a Site.
                </p>
              </div>
            )}

            {!loading && sites.length > 0 && (
              <div className="space-y-3">
                {sites.map((site) => (
                  <button
                    key={site.id}
                    type="button"
                    onClick={() => openSiteDashboard(site)}
                    className="w-full rounded-xl border border-slate-200 bg-slate-50 px-5 py-4 text-left transition hover:border-blue-400 hover:bg-blue-50 hover:shadow-sm"
                  >
                    <h3 className="text-lg font-bold text-slate-900">
                      {site.site_name}
                    </h3>

                    <p className="mt-1 text-sm font-bold uppercase tracking-widest text-blue-700">
                      {site.site_code}
                    </p>

                    <p className="mt-3 text-sm font-semibold text-blue-700">
                      Open Site Dashboard →
                    </p>
                  </button>
                ))}
              </div>
            )}
          </div>
        )}

        {/* Add New Site */}
        {activeOption === "add" && (
          <div>
            <h2 className="mb-5 text-center text-xl font-bold text-slate-800">
              Register New Site
            </h2>

            <form
              onSubmit={handleRegisterSite}
              className="space-y-5"
            >
              <div>
                <label
                  htmlFor="siteName"
                  className="mb-2 block text-sm font-medium text-slate-700"
                >
                  Site Name
                </label>

                <input
                  id="siteName"
                  type="text"
                  value={siteName}
                  onChange={(event) =>
                    handleSiteNameChange(event.target.value)
                  }
                  placeholder="Enter Site Name"
                  className="w-full rounded-lg border border-slate-300 px-4 py-3 outline-none focus:border-blue-600 focus:ring-2 focus:ring-blue-100"
                  required
                />
              </div>

              <div>
                <label
                  htmlFor="siteCode"
                  className="mb-2 block text-sm font-medium text-slate-700"
                >
                  Generated Site Code
                </label>

                <input
                  id="siteCode"
                  type="text"
                  value={siteCode}
                  readOnly
                  placeholder="XXX"
                  className="w-full rounded-lg border border-slate-300 bg-slate-100 px-4 py-3 font-bold uppercase tracking-widest text-slate-800 outline-none"
                />

                <p className="mt-2 text-xs text-slate-500">
                  Automatically generated from the first 3 letters/numbers of Site Name.
                </p>
              </div>

              {error && (
                <p
                  role="alert"
                  className="rounded-lg bg-red-50 p-3 text-sm text-red-700"
                >
                  {error}
                </p>
              )}

              {success && (
                <p
                  role="status"
                  className="rounded-lg bg-green-50 p-3 text-sm text-green-800"
                >
                  {success}
                </p>
              )}

              <button
                type="submit"
                disabled={saving}
                className="w-full rounded-lg bg-emerald-600 px-4 py-3 font-semibold text-white transition hover:bg-emerald-700 disabled:cursor-not-allowed disabled:opacity-60"
              >
                {saving ? "Registering..." : "Register Site"}
              </button>
            </form>
          </div>
        )}

        {!activeOption && (
  <button
    type="button"
    onClick={() => router.push("/")}
    className="mt-6 w-full py-2 text-sm font-medium text-blue-700 hover:underline"
  >
    ← Back
  </button>
)}
</section>
    </main>
  );
}